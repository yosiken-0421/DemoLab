// 依存を jszip だけに絞った最小限の .xlsx 書き出し（Office Open XML）。
import JSZip from 'jszip';

export type CellStyle = 'header' | 'wrap' | 'number' | 'decimal' | 'bold';
export type CellValue = string | number | null | undefined;
export type Cell = CellValue | { v: CellValue; s?: CellStyle };

export interface SheetSpec {
  name: string;
  rows: Cell[][];
  /** 列幅（文字数の目安） */
  widths?: number[];
  /** 1行目を見出しとして固定する */
  freezeHeader?: boolean;
}

const STYLE_INDEX: Record<CellStyle, number> = { header: 1, wrap: 2, number: 3, decimal: 4, bold: 5 };

// XML 1.0 で使えない制御文字を除いてエスケープ
export function xmlEscape(s: string): string {
  return s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function colName(index: number): string {
  let n = index + 1;
  let s = '';
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function cellXml(cell: Cell, ref: string): string {
  const { v, s } = cell !== null && typeof cell === 'object' ? cell : { v: cell, s: undefined };
  const style = s ? ` s="${STYLE_INDEX[s]}"` : '';
  if (v === null || v === undefined || v === '') return s ? `<c r="${ref}"${style}/>` : '';
  if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}"${style}><v>${v}</v></c>`;
  return `<c r="${ref}"${style} t="inlineStr"><is><t xml:space="preserve">${xmlEscape(String(v))}</t></is></c>`;
}

function sheetXml(sheet: SheetSpec): string {
  const rows = sheet.rows
    .map((row, r) => {
      const cells = row.map((c, i) => cellXml(c, `${colName(i)}${r + 1}`)).join('');
      return `<row r="${r + 1}">${cells}</row>`;
    })
    .join('');
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>`
    : '';
  const views = sheet.freezeHeader
    ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    : '';
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">' +
    `${views}${cols}<sheetData>${rows}</sheetData></worksheet>`
  );
}

